const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('src/magi/web/app.js','utf8').split('// Station-wide feeding is intentionally separate')[1];
const elements=new Map();
const $=id=>{if(!elements.has(id))elements.set(id,{value:'',checked:false,disabled:false,open:true,textContent:'',classList:{contains:()=>false},addEventListener(name,fn){this[name]=fn;},checkValidity(){return true;}});return elements.get(id);};
const calls=[];
let response={helper_available:true,busy:false,active:false,enabled:false,settings:{},gps:{latitude:41.1,longitude:-96.1,altitude_msl_m:350.4}};
vm.runInNewContext('// Station-wide feeding is intentionally separate'+source,{$,csrf:'token',setInterval(){},api:async(path,body)=>{calls.push({path,body});return response;}});
(async()=>{
 await $('feeding-refresh').onclick();
 assert.equal(calls.length,1);
 assert.equal(calls[0].body,undefined);
 assert.equal($('feeding-altitude').value,350.4);
 assert.equal($('feeding-enable').disabled,true);
 await $('feeding-enable').onclick();
 assert.equal(calls.length,1);
 $('feeding-username').value='account';
 for(const id of ['feeding-latitude','feeding-longitude','feeding-altitude'])$(id).value=String($(id).value);
 $('feeding-consent').checked=true;
 await $('feeding-enable').onclick();
 assert.equal(calls[1].path,'/api/station/feeding');
 assert.equal(calls[1].body.settings.bandwidth_consent,true);
 assert.equal(calls[1].body.settings.username,'account');
 assert.equal(calls[1].body.settings.altitude_msl_m,350.4);
 assert(!('clientSecret' in calls[1].body.settings));
 assert.equal($('feeding-consent').checked,false);
 response={...response,active:true,enabled:true,username_locked:true,settings:{username:'account'}};
 await $('feeding-refresh').onclick();
 assert.equal($('feeding-disable').disabled,false);
 assert.equal($('feeding-username').disabled,true);
 await $('feeding-disable').onclick();
 assert.equal(JSON.stringify(calls.at(-1).body),'{"action":"disable"}');
 console.log('Feeding UI: explicit consent, separate credentials, GPS MSL, and disable passed.');
})().catch(error=>{console.error(error);process.exitCode=1;});
