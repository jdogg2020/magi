// Exercise actual sensor rendering and mode switching without a live server.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('src/magi/web/app.js','utf8');
const elements=new Map();
const $=id=>{if(!elements.has(id))elements.set(id,{value:'',textContent:'',readOnly:false,placeholder:''});return elements.get(id);};
const context={$,settingsLoaded:true};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('let latestSensors ='),source.indexOf('function renderStatus(')),context);
vm.runInContext(source.slice(source.indexOf('function setLocationMode()'),source.indexOf('let storageBusy =')),context);
$('id-location_source').value='gnss';
$('id-elevation_m').value=0;
context.renderSensors({effective_location:{latitude:40,longitude:-100,elevation_m:0,altitude_effective_source:'manual'}});
assert.equal($('id-elevation_m').value,'');
assert.equal($('id-elevation_m').placeholder,'Waiting for GPS elevation');
assert.equal($('id-elevation_m').readOnly,true);
context.renderSensors({effective_location:{latitude:40,longitude:-100,elevation_m:334.9,altitude_effective_source:'gnss_gga_wgs84'}});
assert.equal($('id-elevation_m').value,334.9);
assert.equal($('star-elevation').value,334.9);
vm.runInContext('manualObserverElevation=123',context);
$('id-location_source').value='manual';
$('id-location_source').onchange();
assert.equal($('id-elevation_m').value,123);
assert.equal($('id-elevation_m').readOnly,false);
$('id-elevation_m').value=150;
$('id-location_source').value='gnss';
$('id-location_source').onchange();
assert.equal($('id-elevation_m').value,334.9);
$('id-location_source').value='manual';
$('id-location_source').onchange();
assert.equal($('id-elevation_m').value,150);
console.log('Automatic elevation waiting, arrival, and manual mode preservation passed');
